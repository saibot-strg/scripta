import AppKit
import ApplicationServices
import Carbon.HIToolbox
import os

/// Puts dictated text into the focused text field of the frontmost app.
///
/// Inside the App Sandbox the Accessibility API can't touch other apps, but
/// posting events can (the "PostEvent" privilege, shown under Accessibility in
/// System Settings). So the text is pasted with a synthetic ⌘V; the previous
/// clipboard is restored afterwards. Outside the sandbox, inserting through the
/// Accessibility API is tried first.
@MainActor
final class TextInserter {
    enum Result: Equatable {
        /// Inserted directly via Accessibility.
        case inserted
        /// Pasted with ⌘V.
        case pasted
        /// No permission to send keystrokes: the text is on the clipboard.
        case copiedToClipboard
        /// A password field (Secure Input) has focus: the text is on the clipboard.
        case blockedBySecureInput
    }

    /// Time the target app gets to read the clipboard before it is restored.
    /// Apps read the pasteboard asynchronously; much shorter delays sometimes
    /// paste the old clipboard instead.
    static let pasteboardRestoreDelay: Duration = .milliseconds(250)

    /// Clipboard managers skip items carrying these types (nspasteboard.org).
    static let privacyMarkers: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    static var isSandboxed: Bool {
        ProcessInfo.processInfo.environment["APP_SANDBOX_CONTAINER_ID"] != nil
    }

    /// Permission to post keyboard events (System Settings › Privacy & Security › Accessibility).
    static var canPostEvents: Bool { CGPreflightPostEventAccess() }

    /// Shows the system prompt that leads to the Accessibility settings.
    @discardableResult
    static func requestPostEventAccess() -> Bool { CGRequestPostEventAccess() }

    private let pasteboard: NSPasteboard

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    func insert(_ text: String) async -> Result {
        guard !text.isEmpty else { return .inserted }
        if IsSecureEventInputEnabled() {
            copyToClipboard(text)
            return .blockedBySecureInput
        }
        if !Self.isSandboxed, insertViaAccessibility(text) {
            return .inserted
        }
        guard Self.canPostEvents else {
            copyToClipboard(text)
            return .copiedToClipboard
        }
        await paste(text)
        return .pasted
    }

    // MARK: - Paste

    func paste(_ text: String) async {
        let snapshot = PasteboardSnapshot(pasteboard)
        let changeCount = write(text, markedPrivate: true)

        await waitForModifierRelease()
        postCommandV()

        try? await Task.sleep(for: Self.pasteboardRestoreDelay)
        // Restore only if nothing else changed the clipboard in the meantime.
        if pasteboard.changeCount == changeCount {
            snapshot.restore(to: pasteboard)
        }
    }

    private func copyToClipboard(_ text: String) {
        write(text, markedPrivate: false)
    }

    @discardableResult
    private func write(_ text: String, markedPrivate: Bool) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if markedPrivate {
            for marker in Self.privacyMarkers { item.setData(Data(), forType: marker) }
        }
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// With push-to-talk the user may still hold ⌃⌥ when the key is released;
    /// posting ⌘V then would arrive as ⌃⌥⌘V.
    private func waitForModifierRelease() async {
        let deadline = ContinuousClock.now + .milliseconds(400)
        while ContinuousClock.now < deadline {
            let flags = CGEventSource.flagsState(.hidSystemState)
            if flags.isDisjoint(with: [.maskControl, .maskAlternate, .maskShift, .maskCommand]) { return }
            try? await Task.sleep(for: .milliseconds(10))
        }
    }

    private func postCommandV() {
        let source = CGEventSource(stateID: .privateState)
        let key = Self.keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V)
        for isDown in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: isDown)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }

    /// The key that types `character` on the current layout (e.g. Dvorak).
    private static func keyCode(for character: String) -> CGKeyCode? {
        for code in 0..<128 {
            let shortcut = KeyShortcut(keyCode: UInt32(code), carbonModifiers: 0)
            if shortcut.displayString.lowercased() == character { return CGKeyCode(code) }
        }
        return nil
    }

    // MARK: - Accessibility (outside the sandbox)

    private func insertViaAccessibility(_ text: String) -> Bool {
        guard AXIsProcessTrusted() else { return false }
        let systemWide = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(systemWide, 0.25)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(systemWide, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return false }
        let element = unsafeDowncast(focused, to: AXUIElement.self)
        var isSettable = DarwinBoolean(false)
        guard AXUIElementIsAttributeSettable(element, kAXSelectedTextAttribute as CFString, &isSettable) == .success,
              isSettable.boolValue else { return false }
        return AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFString) == .success
    }
}
